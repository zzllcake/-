#!/usr/bin/env bash
# =============================================================================
# 中文版代码检查脚本
# 运行全套检查并显示中文状态提示
# =============================================================================

set -o pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color
BOLD='\033[1m'

PASS="${GREEN}✅ 通过${NC}"
FAIL="${RED}❌ 失败${NC}"
SKIP="${YELLOW}⏭️  跳过${NC}"
INFO="${CYAN}ℹ️${NC}"

echo ""
echo -e "${BOLD}========================================${NC}"
echo -e "${BOLD}   🔍 开始全套代码审查检查${NC}"
echo -e "${BOLD}========================================${NC}"
echo ""

# --------------------------------------------------
# 1. ESLint 代码规范检查
# --------------------------------------------------
echo -e "${CYAN}[1/4]${NC} ${BOLD}代码规范检查 (ESLint)...${NC}"
if npm run lint 2>&1; then
  echo -e "  ${PASS} 代码规范正确"
else
  echo -e "  ${FAIL} 存在代码规范问题，运行 ${BOLD}npm run lint:fix${NC} 自动修复"
fi
echo ""

# --------------------------------------------------
# 2. Prettier 格式检查
# --------------------------------------------------
echo -e "${CYAN}[2/4]${NC} ${BOLD}代码格式检查 (Prettier)...${NC}"
if npm run format:check 2>&1; then
  echo -e "  ${PASS} 代码格式正确"
else
  echo -e "  ${FAIL} 存在格式问题，运行 ${BOLD}npm run format${NC} 自动格式化"
fi
echo ""

# --------------------------------------------------
# 3. TypeScript 类型检查
# --------------------------------------------------
echo -e "${CYAN}[3/4]${NC} ${BOLD}类型安全检查 (TypeScript)...${NC}"
if npm run typecheck 2>&1; then
  echo -e "  ${PASS} 类型安全"
else
  echo -e "  ${FAIL} 存在类型错误"
fi
echo ""

# --------------------------------------------------
# 4. 单元测试
# --------------------------------------------------
echo -e "${CYAN}[4/4]${NC} ${BOLD}单元测试 (Vitest)...${NC}"
if npm test 2>&1; then
  echo -e "  ${PASS} 全部测试通过"
else
  echo -e "  ${FAIL} 有测试未通过"
fi
echo ""

# --------------------------------------------------
# 汇总结果
# --------------------------------------------------
echo -e "${BOLD}========================================${NC}"
echo -e "${BOLD}   📋 审查完成${NC}"
echo -e "${BOLD}========================================${NC}"
echo ""
echo "  本地通过了？ → 提交推送创建 PR 即可触发 GitHub 自动审查"
echo "  有错误？     → 查看上方红色 ❌ 提示，修复后重新运行"
echo ""
